import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {createOfflineShopContext,readOfflineShopContext,offlineShopRecord,permitsOfflineShopFallback,saveOfflineShop,loadOfflineShop,clearOfflineShop}=require(process.env.GST_TEST_BUILD+'/offline-shop-context.js');
const {permissionsFor}=require(process.env.GST_TEST_BUILD+'/permissions.js');
const now=Date.now();
const shop={id:'shop',name:'Suresh Store',category:'stationary',ownerId:'owner',createdAt:'2026-01-01T00:00:00Z',role:'OWNER',managerInviteCode:'secret',helperInviteCode:'secret',address:'Private address'};
const context=createOfflineShopContext('owner','session-a',shop,now);
const raw=JSON.stringify(context);
assert.ok(!raw.includes('secret'));assert.ok(!raw.includes('Private address'));
assert.equal(readOfflineShopContext(raw,'other','session-a',now),null);
assert.equal(readOfflineShopContext(raw,'owner','session-b',now),null);
assert.equal(readOfflineShopContext(raw,'owner','session-a',now-1),null);
assert.equal(readOfflineShopContext(raw,'owner','session-a',now+7*86400000+1),null);
assert.equal(readOfflineShopContext('{','owner','session-a',now),null);
assert.equal(readOfflineShopContext(JSON.stringify({...context,role:'ADMIN'}),'owner','session-a',now),null);
assert.throws(()=>createOfflineShopContext('other','session-a',shop,now),/invalid/);
const restored=offlineShopRecord(context);
assert.equal(restored.role,'HELPER');assert.equal(restored.managerInviteCode,null);
const perms=permissionsFor('OWNER',true);
assert.equal(perms.canSell,true);
for(const permission of ['canAdjustStock','canEditProducts','canManageCustomers','canManageStaff','canManageShop','canSeeCost','canSeeReports','canVoidOrReturn'])assert.equal(perms[permission],false,permission);
for(const status of [401,403,404,400,429,500])assert.equal(permitsOfflineShopFallback({status}),false);
for(const status of [408,502,503,504])assert.equal(permitsOfflineShopFallback({status}),true);
assert.equal(permitsOfflineShopFallback(new TypeError('Failed to fetch')),true);
assert.equal(permitsOfflineShopFallback(new TypeError('Programming error')),false);
const entries=new Map();
const storage={getItem:key=>entries.get(key)??null,setItem:(key,value)=>entries.set(key,value),removeItem:key=>entries.delete(key)};
assert.equal(saveOfflineShop(storage,context),true);
assert.equal(loadOfflineShop(storage,'owner','session-a').shop.id,'shop');
assert.equal(loadOfflineShop(storage,'owner','session-b'),null);
clearOfflineShop(storage,'owner');assert.equal(entries.size,0);
const denied={...storage,getItem:()=>{throw Error('denied');},setItem:()=>{throw Error('denied');}};
assert.equal(loadOfflineShop(denied,'owner','session-a'),null);assert.equal(saveOfflineShop(denied,context),false);
assert.equal(saveOfflineShop({...storage,getItem:()=>null},context),false);assert.equal(entries.size,0);
console.log('Offline shop context: account/session scope, expiry, minimal routing data, reduced permissions, denial and verified storage passed.');
