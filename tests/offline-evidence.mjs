import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {webcrypto} from 'node:crypto';
const require=createRequire(import.meta.url);globalThis.crypto??=webcrypto;
const {createOfflineEvidence}=require(process.env.GST_TEST_BUILD+'/offline-evidence.js');
let at=Date.now(),current=true,fallbacks=0;
const entries=new Map();
const store={read:async key=>entries.get(key),write:async(key,value)=>entries.set(key,value)};
const scope={actorId:'actor',sessionId:'session',isCurrent:()=>current,onFallback:()=>fallbacks++};
const cache=createOfflineEvidence(scope,store,()=>at);
const validate=value=>!!value&&value.shopId==='shop'&&typeof value.total==='number';
const fresh={shopId:'shop',total:4,cost:100};
const network=new TypeError('Failed to fetch');
const unavailable=async()=>{throw network;};
assert.equal(await cache.read('shop','catalog',async()=>fresh,validate,value=>({...value,cost:undefined})),fresh);
assert.equal((await cache.read('shop','catalog',unavailable,validate)).cost,undefined);
assert.equal(fallbacks,1);
for(const changed of [{actorId:'other'},{sessionId:'other'}]){
 const other=createOfflineEvidence({...scope,...changed},store,()=>at);
 await assert.rejects(other.read('shop','catalog',unavailable,validate),error=>error===network);
}
await assert.rejects(cache.read('other','catalog',unavailable,validate),error=>error===network);
const entry=[...entries.values()][0];entry.value.total=100;
await assert.rejects(cache.read('shop','catalog',unavailable,validate),error=>error===network);
await cache.read('shop','catalog',async()=>fresh,validate);
at+=7*86400000+1;await assert.rejects(cache.read('shop','catalog',unavailable,validate),error=>error===network);
at=Date.now();await cache.read('shop','catalog',async()=>fresh,validate);
const forbidden={status:403};await assert.rejects(cache.read('shop','catalog',async()=>{throw forbidden;},validate),error=>error===forbidden);
await assert.rejects(cache.read('shop','catalog',unavailable,validate),error=>error===network);
const denied=createOfflineEvidence(scope,{read:async()=>{throw Error('denied');},write:async()=>{throw Error('denied');}},()=>at);
assert.equal(await denied.read('shop','catalog',async()=>fresh,validate),fresh);
await assert.rejects(denied.read('shop','catalog',unavailable,validate),error=>error===network);
let resolve;
const loading=cache.read('shop','catalog',()=>new Promise(done=>{resolve=done;}),validate);
current=false;resolve(fresh);await assert.rejects(loading,/scope_changed/);
current=true;
let finishWrite;
const delayed=createOfflineEvidence(scope,{read:store.read,write:async(key,value)=>{if(value)await new Promise(done=>{finishWrite=()=>{entries.set(key,value);done();};});else entries.set(key,value);}},()=>at);
const writing=delayed.read('shop','catalog',async()=>fresh,validate);
while(!finishWrite)await new Promise(done=>setTimeout(done,1));
current=false;finishWrite();await assert.rejects(writing,/scope_changed/);current=true;
await assert.rejects(cache.read('shop','catalog',unavailable,validate),error=>error===network);
console.log('Offline evidence: scope, integrity, age, auth rejection, storage refusal and stale response/write invalidation passed.');
